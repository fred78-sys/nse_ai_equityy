"""Forecasts and recommendations.

Expected returns are NOT taken at face value from the model.  They are calibrated against what
the model's signals actually delivered out-of-sample (Fama-MacBeth slopes on matured 3-month
outcomes) and shrunk by statistical significance -- so with no demonstrated skill, every stock's
expected excess return collapses towards zero and the portfolio towards the index.

The return *distribution* is generated by a vol-scaled block bootstrap of each stock's own
history (keeps fat tails, volatility clustering and NSE's zero-return stale days).
"""
from __future__ import annotations

import warnings

import numpy as np
import pandas as pd

from .features import ALL_FEATURES, Panel
from .strategies import ML_IDX, explain
from .walkforward import WFResult


# --------------------------------------------------------------------------------------
# calibration
# --------------------------------------------------------------------------------------
def fama_macbeth(x: np.ndarray, y: np.ndarray, elig: np.ndarray, rows) -> dict:
    slopes, ics = [], []
    for r in rows:
        m = elig[r] & np.isfinite(y[r]) & np.isfinite(x[r])
        if m.sum() < 8 or np.std(x[r][m]) < 1e-9:
            continue
        yy = y[r][m] - y[r][m].mean()
        yy = np.clip(yy, -1.0, 1.0)
        xx = x[r][m]
        slopes.append(np.cov(xx, yy)[0, 1] / np.var(xx, ddof=1))
        ics.append(pd.Series(xx).corr(pd.Series(yy), method="spearman"))
    n = len(slopes)
    if n < 8:
        return {"beta": 0.0, "t": 0.0, "ic": np.nan, "ic_t": np.nan, "n": n}
    sl, ic = np.array(slopes), np.array(ics)
    n_eff = max(n / 3.0, 2)                                  # 3-month labels sampled monthly overlap
    t = sl.mean() / (sl.std(ddof=1) / np.sqrt(n_eff) + 1e-12)
    ict = ic.mean() / (ic.std(ddof=1) / np.sqrt(n_eff) + 1e-12)
    return {"beta": float(sl.mean()), "t": float(t), "ic": float(ic.mean()), "ic_t": float(ict), "n": n}


def calibrate(res: WFResult) -> dict:
    P = res.P
    fw = P.fwd3
    with np.errstate(all="ignore"), warnings.catch_warnings():
        warnings.simplefilter("ignore", RuntimeWarning)
        mu = np.nanmean(np.where(P.elig, fw, np.nan), axis=1, keepdims=True)
    rel = np.where(np.isfinite(fw), fw - mu, np.nan)
    rows = [r for r in range(res.r_start, P.R - 3) if np.isfinite(fw[r]).any()]
    return {"ensemble": fama_macbeth(res.comp, rel, P.elig, rows),
            "ml": fama_macbeth(P.cube[ML_IDX].astype(float), rel, P.elig, rows)}


# --------------------------------------------------------------------------------------
# generative simulation
# --------------------------------------------------------------------------------------
def simulate_returns(daily_ret: pd.Series, mu_h: float, h: int, paths: int, block: int,
                     rng: np.random.Generator) -> np.ndarray:
    r = daily_ret.dropna().to_numpy()[-756:]
    if len(r) < 120:
        return np.full(paths, np.nan)
    lam, s2 = 0.94, np.var(r[:30]) + 1e-8
    sig = np.empty(len(r))
    for i, v in enumerate(r):                                # EWMA vol (RiskMetrics)
        sig[i] = np.sqrt(s2)
        s2 = lam * s2 + (1 - lam) * v * v
    z = r / np.maximum(sig, 1e-4)
    sig_now = 0.5 * np.sqrt(s2) + 0.5 * r.std()
    nb = int(np.ceil(h / block))
    starts = rng.integers(0, len(z) - block, size=(paths, nb))
    idx = (starts[:, :, None] + np.arange(block)[None, None, :]).reshape(paths, -1)[:, :h]
    sim = z[idx] * sig_now
    sim = np.clip(sim, -0.3, 0.3)
    cum = np.prod(1 + sim, axis=1) - 1
    shift = (mu_h - cum.mean()) / h                           # re-centre on the calibrated expectation
    return np.prod(1 + sim + shift, axis=1) - 1


# --------------------------------------------------------------------------------------
# recommendations
# --------------------------------------------------------------------------------------
def recommend(res: WFResult, cfg: dict, as_of=None) -> tuple[pd.DataFrame, dict]:
    P, F, mk = res.P, cfg["forecast"], cfg["market"]
    rng = np.random.default_rng(cfg["learning"]["seed"] + 1)
    row = P.R - 1
    cal = calibrate(res)
    h = F["horizon_days"]
    cash_h = (1 + P.cash_rate[row]) ** (h / 252) - 1
    erp_h = mk["equity_risk_premium"] * h / 252
    x = {"ensemble": res.comp[row], "ml": P.cube[ML_IDX, row].astype(float)}
    shr = {k: float(np.clip(cal[k]["t"] / 2.0, 0, 1)) for k in x}
    denom = max(1.0, sum(shr.values()))
    ex_excess = sum(shr[k] * cal[k]["beta"] * x[k] for k in x) / denom
    ex_excess = np.where(P.elig[row], ex_excess, 0.0)
    W = res.W_oos[row]
    fin = res.final
    drivers = explain([r.genome for r in fin["alive"]], fin["a"] * fin["conviction"], P, row)
    tier = res.metrics["tier"]
    conv_label = {"MODERATE EVIDENCE": "MEDIUM", "WEAK EVIDENCE": "LOW-MEDIUM"}.get(tier, "LOW (index-like)")
    sector = P.meta["sector"] if P.meta is not None else pd.Series("", index=P.tickers)
    name = P.meta["name"] if P.meta is not None else pd.Series("", index=P.tickers)
    rets = P.px_df / P.px_df.shift(1) - 1
    rows = []
    z_all = x["ensemble"]
    for i, t in enumerate(P.tickers):
        if not P.elig[row, i] and W[i] <= 0:
            continue
        mu_h = cash_h + erp_h + ex_excess[i]
        sim = simulate_returns(rets[t], mu_h, h, F["mc_paths"], F["bootstrap_block"], rng)
        ok = np.isfinite(sim).all()
        q = np.quantile(sim, [.1, .5, .9]) if ok else [np.nan] * 3
        tail = np.sort(sim)[: max(1, int(.05 * len(sim)))].mean() if ok else np.nan
        adv = P.adv_value[row, i]
        kes = W[i] * F["capital_kes"]
        days = kes / (mk["participation_rate"] * adv) if np.isfinite(adv) and adv > 0 else np.nan
        agree = np.sign(x["ensemble"][i]) == np.sign(x["ml"][i]) and abs(x["ml"][i]) > 0.2
        rows.append({
            "ticker": t, "name": name.get(t, ""), "sector": sector.get(t, ""), "price": float(P.last_price[i]),
            "target_weight": float(W[i]), "suggested_kes": float(kes),
            "exp_3m_return": float(mu_h), "exp_3m_excess_vs_market": float(ex_excess[i]),
            "p_gain": float((sim > 0).mean()) if ok else np.nan,
            "p_beat_tbill": float((sim > cash_h).mean()) if ok else np.nan,
            "p10": q[0], "p50": q[1], "p90": q[2], "cvar5": tail,
            "signal_z": float(z_all[i]), "ml_z": float(x["ml"][i]), "models_agree": bool(agree),
            "vol_ann": float(P.vol_ann[row, i]) if np.isfinite(P.vol_ann[row, i]) else np.nan,
            "adv_kes": float(adv) if np.isfinite(adv) else np.nan, "days_to_enter": days,
            "drivers": "; ".join(f"{n}" for n, _ in drivers[i]) if conv_label != "LOW (index-like)" or W[i] > 0 else "",
        })
    df = pd.DataFrame(rows)
    mb = F["min_buy_weight"]
    def action(r):
        if r.target_weight >= mb: return "BUY / HOLD"
        if r.target_weight > 0: return "SMALL HOLD"
        if r.signal_z < -0.5 and r.exp_3m_excess_vs_market < 0 and r.p_beat_tbill < 0.45: return "AVOID"
        return "NEUTRAL"
    df["action"] = df.apply(action, axis=1)
    df["confidence"] = np.where(df["action"].isin(["BUY / HOLD", "SMALL HOLD"]), conv_label, "-")
    df["liquidity_flag"] = np.where(df["days_to_enter"] > 3, "THIN: >3 days to enter", "ok")
    df = df.sort_values(["target_weight", "signal_z"], ascending=False).reset_index(drop=True)
    info = {"as_of": str(P.rb_dates[row])[:10], "horizon_days": h, "calibration": cal, "shrink": shr,
            "tier": tier, "conviction_label": conv_label, "strategy_conviction": float(fin["conviction"]),
            "cash_h": float(cash_h), "cash_weight": float(max(0.0, 1 - W.sum()))}
    return df, info
